"""身份类问题的固定回答。

模型被问到「谁开发了你」时会自行编造公司信息，因此身份问题由服务端直接
返回固定文案（B 方案）；system prompt 中的身份声明（A 方案）作为兜底，
避免模型在其它问法下自由发挥。
"""

from __future__ import annotations

import re
import unicodedata
from typing import Optional

ASSISTANT_NAME = "安小记"

ASSISTANT_IDENTITY_PROMPT = f"""关于你的身份：你的名字是「{ASSISTANT_NAME}」，由上海交通大学医学院附属仁济医院、三十天科技（山西）股份有限公司、福芯高照（上海）科技有限公司三方联合开发。
当用户询问你是谁、谁创造/开发了你、你属于哪家公司或团队时，只能说明以上三方合作关系，不得编造其他公司名称、所在地、隶属关系、成立时间或团队成员。
"""

IDENTITY_ANSWER = """我是由以下三方联合开发的：

✅ **上海交通大学医学院附属仁济医院**
——提供临床医学指导、诊疗规范支持与真实医疗场景验证，确保我的医学逻辑严谨、贴近实际需求。

✅ **三十天科技（山西）股份有限公司**
——负责人工智能底层技术研发、大模型训练与工程化落地，赋予我理解报告、推理症状、生成专业建议的能力。

✅ **福芯高照（上海）科技有限公司**
——专注医疗健康领域的 AI 产品设计与合规建设，主导我的交互体验、数据安全架构及医疗级内容审核体系。

简言之：

🧠 仁济医院是“医学大脑”

⚙️ 三十天科技是“技术引擎”

❤️ 福芯高照是“产品心脏”

我们共同打造了「安小记」——一个既懂医学术语、也听得懂你日常表达的健康助手。

如你有任何检查单、症状描述或用药疑问，欢迎随时告诉我，我会以专业又清晰的方式陪你一起梳理 🌟

需要现在帮你看看什么吗？"""

_MAKE_WORDS = "开发|创造|研发|制作|打造|设计|训练|构建|做"

_SELF = rf"(?:你|您|{ASSISTANT_NAME})"

_IDENTITY_PATTERNS = (
    # 谁开发了你 / 哪家公司创造了你 / 什么团队研发的安小记
    rf"(?:谁|哪位|哪家|哪个|什么)(?:公司|团队|机构|单位|组织)?[^。！？\n]{{0,6}}(?:{_MAKE_WORDS})(?:了|的)?{_SELF}",
    # 你是由谁开发的 / 你被哪家公司研发的
    rf"{_SELF}(?:是|由|被)[^。！？\n]{{0,10}}(?:{_MAKE_WORDS})(?:的|出来)",
    # 你的开发团队 / 研发方是谁
    r"(?:你|您)的(?:开发|研发|创造|设计)(?:者|团队|公司|方|厂商)",
    rf"(?:{_MAKE_WORDS})(?:团队|者|公司|方)(?:是)?(?:谁|哪家|哪个)",
    # 你是哪家公司/什么团队
    r"(?:你|您)(?:是|属于)(?:哪|什么)(?:家|个)?(?:公司|团队|机构|单位)",
    # 你是谁 / 安小记是谁 / 叫什么名字（排除「谁家的孩子」这类非身份问法）
    rf"{_SELF}(?:到底)?(?:是谁(?!家)|叫什么(?:名字)?)",
    # 你是什么 AI / 什么助手
    r"(?:你|您)(?:到底)?是(?:什么|啥|哪种)(?:ai|人工智能|机器人|大模型|模型|助手|软件|app|产品)",
    r"(?:简单|简要|大概|随便)?(?:介绍|说说|讲讲)(?:一下|下)?(?:你|您)自己",
    r"自我介绍",
    # 你们公司是哪家 / 贵团队是谁
    r"(?:你们|贵)(?:公司|团队|机构|单位)(?:是)?(?:哪家|哪个|什么|谁)",
    r"(?:你|您)是(?:真人|机器人|人工智能|真人医生)(?:吗|么)",
)


def _normalize(text: str) -> str:
    return unicodedata.normalize("NFKC", str(text or "")).strip()


def is_identity_question(message: str) -> bool:
    """判断是否为询问助手身份/开发方的问题。"""
    value = _normalize(message)
    if not value or len(value) > 60:
        return False
    return any(re.search(pattern, value, re.I) for pattern in _IDENTITY_PATTERNS)


def build_identity_answer(message: str) -> Optional[str]:
    """身份类问题返回固定文案，其它问题返回 None。"""
    return IDENTITY_ANSWER if is_identity_question(message) else None
